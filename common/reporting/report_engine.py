# ── Severity ordering ────────────────────────────────────────────────────────

_SEVERITY_ORDER = {
    "Critical":      0,
    "High":          1,
    "Medium":        2,
    "Low":           3,
    "Informational": 4,
}

_SEVERITY_COLORS = {
    "Critical":      ("#7030A0", "#ffffff"),  # (bg, text)
    "High":          ("#FF0000", "#ffffff"),
    "Medium":        ("#FF9900", "#000000"),
    "Low":           ("#FFFF00", "#000000"),
    "Informational": ("#92D050", "#000000"),
}

_CONFIDENCE_COLORS = {
    "HIGH":       "#27ae60",
    "MEDIUM":     "#f39c12",
    "LOW":        "#e67e22",
    "UNVERIFIED": "#95a5a6",
}


# ── Config dataclass ─────────────────────────────────────────────────────────

@dataclass
class ReportConfig:
    """Configuration for a single report generation run."""
    engagement:     str         = "Untitled Engagement"
    target:         str         = ""
    tester:         str         = "Forge Suite v5 APEX"
    client:         str         = ""
    classification: str         = "CONFIDENTIAL — FOR AUTHORIZED USE ONLY"
    scope:          list[str]   = field(default_factory=list)
    methodology:    list[str]   = field(default_factory=list)
    formats:        list[str]   = field(default_factory=lambda: ["html", "pdf"])
    output_dir:     str         = "."
    include_exec_summary: bool  = True
    include_remediation_roadmap: bool = True
    include_mitre_appendix: bool = True
    include_unverified: bool    = False  # if False, LOW/UNVERIFIED suppressed from default report
    logo_path:      str | None  = None

    def __post_init__(self) -> None:
        if not self.methodology:
            self.methodology = [
                "OWASP Testing Guide v4.2",
                "PTES (Penetration Testing Execution Standard)",
                "MITRE ATT&CK Framework",
                "NIST SP 800-115",
            ]


# ── Main engine ──────────────────────────────────────────────────────────────

class ReportEngine:
    """Forge Suite report engine — PDF/HTML report generation.

    Usage::

        engine = ReportEngine(findings, config)
        paths  = await engine.generate()
        # paths = {"html": "/path/report.html", "pdf": "/path/report.pdf"}
    """

    def __init__(
        self,
        findings: list[dict[str, Any]],
        config: ReportConfig,
    ) -> None:
        normalised = [normalise_finding(f) for f in findings]
        visible = normalised if config.include_unverified else [
            f for f in normalised if should_include_default(f)
        ]
        # Track suppressed counts for executive summary context
        self._suppressed_count = len(findings) - len(visible)
        self.findings   = sorted(
            visible,
            key=lambda f: (
                -(float(f.get("vpr_score") or f.get("cvss_v31_score") or 0.0)),
                _SEVERITY_ORDER.get(f.get("severity", "Informational"), 99),
            ),
        )
        self.config     = config
        self.output_dir = Path(config.output_dir)
        self.output_dir.mkdir(parents=True, exist_ok=True)
        self.generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    async def generate(self) -> dict[str, str]:
        """Generate all configured report formats asynchronously.

        Returns:
            Dict mapping format name to absolute output path.
        """
        paths: dict[str, str] = {}

        # Generate executive summary via ForgeBrain narrator (optional)
        exec_summary = ""
        if self.config.include_exec_summary:
            exec_summary = await self._generate_exec_summary()

        # Build enriched findings (embed screenshots as b64)
        enriched = self._enrich_findings()

        # Severity summary counts
        summary = self._severity_summary(enriched)

        # Remediation roadmap (sorted by priority)
        roadmap = self._build_remediation_roadmap(enriched) if self.config.include_remediation_roadmap else []

        # MITRE ATT&CK TTP appendix
        mitre_ttps = self._collect_mitre_ttps(enriched) if self.config.include_mitre_appendix else []

        # Logo base64 (if provided)
        logo_b64 = self._load_logo()

        context = {
            "product_version":   VERSION,
            "engagement":        self.config.engagement,
            "target":            self.config.target,
            "tester":            self.config.tester,
            "client":            self.config.client,
            "classification":    self.config.classification,
            "scope":             self.config.scope,
            "methodology":       self.config.methodology,
            "generated_at":      self.generated_at,
            "findings":          enriched,
            "summary":           summary,
            "exec_summary":      exec_summary,
            "roadmap":           roadmap,
            "mitre_ttps":        mitre_ttps,
            "severity_colors":   _SEVERITY_COLORS,
            "logo_b64":          logo_b64,
            "total_findings":    len(enriched),
            "suppressed_count":  self._suppressed_count,
        }

        if "html" in self.config.formats:
            html_path = self._generate_html(context)
            if html_path:
                paths["html"] = html_path

        if "pdf" in self.config.formats:
            # PDF is derived from HTML — ensure HTML is generated first
            html_path = paths.get("html") or self._generate_html(context)
            pdf_path = self._generate_pdf(html_path)
            if pdf_path:
                paths["pdf"] = pdf_path

        if "json" in self.config.formats:
            json_path = self._generate_json(context)
            if json_path:
                paths["json"] = json_path

        for fmt, path in paths.items():
            log.info("Report generated [%s]: %s", fmt.upper(), path)

        return paths

    # ── HTML generation ───────────────────────────────────────────────────────

    def _generate_html(self, ctx: dict[str, Any]) -> str | None:
        """Render HTML report via Jinja2 (falls back to inline builder)."""
        try:
            from jinja2 import Environment, BaseLoader, select_autoescape
            env = Environment(
                loader=BaseLoader(),
                autoescape=select_autoescape(["html"]),
            )
            template = env.from_string(_HTML_TEMPLATE)
            html = template.render(**ctx)
        except ImportError:
            log.warning("Jinja2 not available — using inline HTML builder")
            html = _build_html_inline(ctx)
        except Exception as exc:
            log.error("HTML template render failed: %s", exc)
            html = _build_html_inline(ctx)

        path = self.output_dir / "report.html"
        path.write_text(html, encoding="utf-8")
        return str(path)

    # ── PDF generation ────────────────────────────────────────────────────────

    def _generate_pdf(self, html_path: str | None) -> str | None:
        """Render PDF via WeasyPrint from the HTML file."""
        if not html_path or not Path(html_path).exists():
            log.warning("PDF skipped — no HTML source at %s", html_path)
            return None
        try:
            from weasyprint import HTML as WP_HTML, CSS as WP_CSS
            pdf_path = self.output_dir / "report.pdf"
            WP_HTML(filename=html_path).write_pdf(
                str(pdf_path),
                stylesheets=[WP_CSS(string=_PDF_CSS_OVERRIDE)],
            )
            return str(pdf_path)
        except ImportError:
            log.warning("WeasyPrint not installed — PDF generation skipped. "
                        "Install with: pip install weasyprint")
            return None
        except Exception as exc:
            log.error("PDF generation failed: %s", exc)
            return None

    # ── JSON export ───────────────────────────────────────────────────────────

    def _generate_json(self, ctx: dict[str, Any]) -> str | None:
        """Export structured JSON report."""
        out = {
            "generated_at":   ctx["generated_at"],
            "engagement":     ctx["engagement"],
            "target":         ctx["target"],
            "tester":         ctx["tester"],
            "classification": ctx["classification"],
            "summary":        ctx["summary"],
            "total_findings": ctx["total_findings"],
            "findings":       [
                {k: v for k, v in f.items() if k != "screenshot_b64"}
                for f in ctx["findings"]
            ],
            "exec_summary":   ctx["exec_summary"],
            "roadmap":        ctx["roadmap"],
            "mitre_ttps":     ctx["mitre_ttps"],
        }
        path = self.output_dir / "report.json"
        path.write_text(json.dumps(out, indent=2, default=str), encoding="utf-8")
        return str(path)

    # ── Support helpers ────────────────────────────────────────────────────────

    def _enrich_findings(self) -> list[dict[str, Any]]:
        """Embed screenshots as base64 data URIs and normalise fields."""
        enriched: list[dict[str, Any]] = []
        for i, f in enumerate(self.findings, 1):
            row = dict(f)
            row["_index"] = i
            ev = dict(f.get("evidence") or {})
            extra = dict(ev.get("extra") or {})
            sp = ev.get("screenshot_path")
            if sp and Path(sp).exists():
                try:
                    data = base64.b64encode(Path(sp).read_bytes()).decode()
                    row["screenshot_b64"] = f"data:image/png;base64,{data}"
                except Exception:
                    row["screenshot_b64"] = None
            else:
                row["screenshot_b64"] = None
            row["evidence"] = ev

            # Severity colour lookup
            sev = f.get("severity", "Informational")
            row["_sev_bg"], row["_sev_fg"] = _SEVERITY_COLORS.get(sev, ("#cccccc", "#000000"))

            # VPR: use stored vpr field, or derive from CVSS score
            cvss = f.get("cvss_v31_score") or 0.0
            row["vpr_score"] = f.get("vpr_score") or cvss or 0.0
            row["vpr_priority"] = f.get("vpr_priority") or f.get("vpr") or _vpr_label(cvss)
            row["_vpr_label"] = row["vpr_priority"]

            # Normalise new first-class fields with safe defaults
            row["confidence"]   = (
                f.get("confidence")
                or (f.get("verification") or {}).get("confidence")
                or extra.get("fp_confidence")
                or "UNVERIFIED"
            )
            row["status"]       = f.get("status", "open")
            row["url"]          = f.get("url") or f.get("target", "")
            row["verification"] = f.get("verification") or {
                "confidence": row["confidence"],
                "evidence": extra.get("fp_evidence", []),
            }

            # Confidence badge styling
            row["_conf_color"] = _CONFIDENCE_COLORS.get(row["confidence"], "#888888")

            enriched.append(row)
        return enriched

    def _severity_summary(self, findings: list[dict]) -> dict[str, int]:
        summary = {"Critical": 0, "High": 0, "Medium": 0, "Low": 0, "Informational": 0}
        for f in findings:
            sev = f.get("severity", "Informational")
            summary[sev] = summary.get(sev, 0) + 1
        return summary

    def _build_remediation_roadmap(self, findings: list[dict]) -> list[dict[str, Any]]:
        """Return ordered remediation steps — Critical/High first, grouped by finding."""
        roadmap: list[dict[str, Any]] = []
        seen_remediations: set[str] = set()
        for f in findings:
            rem = f.get("remediation", "").strip()
            if rem and rem not in seen_remediations:
                seen_remediations.add(rem)
                roadmap.append({
                    "priority": len(roadmap) + 1,
                    "title":    f.get("title", "Unknown Finding"),
                    "severity": f.get("severity", "Informational"),
                    "sev_bg":   f.get("_sev_bg", "#cccccc"),
                    "sev_fg":   f.get("_sev_fg", "#000000"),
                    "cvss":     f.get("cvss_v31_score") or 0.0,
                    "vpr_score": f.get("vpr_score") or 0.0,
                    "vpr_priority": f.get("vpr_priority") or f.get("_vpr_label", ""),
                    "remediation": rem,
                    "references":  f.get("references", []),
                })
        return roadmap

    def _collect_mitre_ttps(self, findings: list[dict]) -> list[dict[str, str]]:
        """Deduplicate and describe MITRE ATT&CK TTPs across all findings."""
        seen: dict[str, dict[str, str]] = {}
        for f in findings:
            for ttp in f.get("mitre_attack", []):
                if ttp not in seen:
                    seen[ttp] = {
                        "ttp":     ttp,
                        "title":   f.get("title", ""),
                        "finding": f.get("title", ""),
                    }
        return list(seen.values())

    async def _generate_exec_summary(self) -> str:
        """Auto-generate executive summary via ForgeBrain narrator."""
        try:
            from common.brain.narrator import Narrator
            narrator = Narrator()
            if not narrator.brain.available:
                return _default_exec_summary(self.findings, self.config)
            summary = await narrator.summarise_engagement(
                findings=self.findings,
                engagement=self.config.engagement,
                target=self.config.target,
            )
            return summary or _default_exec_summary(self.findings, self.config)
        except Exception as exc:
            log.debug("ForgeBrain narrator unavailable: %s", exc)
            return _default_exec_summary(self.findings, self.config)

    def _load_logo(self) -> str | None:
        """Load logo PNG as base64 data URI if path is configured."""
        if not self.config.logo_path:
            return None
        try:
            p = Path(self.config.logo_path)
            if p.exists():
                data = base64.b64encode(p.read_bytes()).decode()
                return f"data:image/png;base64,{data}"
        except Exception:
            pass
        return None


# ── VPR helper ────────────────────────────────────────────────────────────────

def _vpr_label(cvss: float) -> str:
    """Map CVSS score to VPR priority label."""
    if cvss >= 9.0: return "CRITICAL"
    if cvss >= 7.0: return "HIGH"
    if cvss >= 4.0: return "MEDIUM"
    if cvss > 0.0:  return "LOW"
    return "INFO"


# ── Default executive summary (when AI is unavailable) ────────────────────────

def _default_exec_summary(findings: list[dict], config: ReportConfig) -> str:
    """Generate a template-driven executive summary."""
    severity_counts: dict[str, int] = {
        "Critical": 0, "High": 0, "Medium": 0, "Low": 0, "Informational": 0
    }
    for f in findings:
        sev = f.get("severity", "Informational")
        severity_counts[sev] = severity_counts.get(sev, 0) + 1

    crit = severity_counts.get("Critical", 0)
    high = severity_counts.get("High", 0)
    total = len(findings)

    risk_level = (
        "CRITICAL" if crit > 0 else
        "HIGH"     if high > 0 else
        "MEDIUM"   if severity_counts.get("Medium", 0) > 0 else
        "LOW"
    )

    return (
        f"A penetration test was conducted against {config.target or 'the target environment'} "
        f"as part of engagement '{config.engagement}'. "
        f"The assessment identified {total} finding(s) across multiple risk categories, "
        f"including {crit} critical and {high} high severity issue(s). "
        f"The overall risk posture of the target is assessed as {risk_level}. "
        f"Immediate remediation is recommended for all Critical and High severity findings "
        f"to reduce the risk of unauthorized access and data compromise. "
        f"Full technical details, reproduction steps, and remediation guidance are provided "
        f"in the findings section of this report."
    )


