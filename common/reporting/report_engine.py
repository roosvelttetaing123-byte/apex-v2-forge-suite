"""Forge Suite v5 APEX — Report Engine.

Generates professional penetration test reports in PDF and HTML from a
list of Finding dicts (as returned by Finding.to_dict()).

Features:
    • VPR-sorted findings table (Critical → High → Medium → Low → Info)
    • CVSS 3.1 and CVSS 4.0 score columns with colour-coded badges
    • Embedded base64 evidence screenshots (self-contained HTML)
    • Remediation roadmap section — ordered by VPR priority
    • Executive summary auto-generated by ForgeBrain narrator
    • Appendix: MITRE ATT&CK TTPs, scope, methodology
    • PDF via WeasyPrint; HTML via Jinja2 with inline CSS

FOR AUTHORIZED PENETRATION TESTING AND RED TEAM OPERATIONS ONLY.
"""
from __future__ import annotations

